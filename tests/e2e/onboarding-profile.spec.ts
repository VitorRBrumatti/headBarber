import { test, expect } from '@playwright/test'
import { executeLocalSql, seedBookingFixture } from './barber-service-fixture'

test('new shop configures its booking profile before dashboard, then edits it in settings', async ({ page, context }) => {
  test.setTimeout(60_000)
  const fixture = await seedBookingFixture()
  executeLocalSql(`update public.profiles set barbershop_id=null where barbershop_id='${fixture.barbershopId}'`)
  await page.goto('/login')
  await page.locator('#login-email').fill(fixture.ownerEmail)
  await page.locator('#login-password').fill(fixture.ownerPassword)
  await page.locator('form').getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForURL('**/onboarding')
  const name = `Studio Inicial ${crypto.randomUUID().slice(0, 8)}`
  await page.getByLabel('Nome da barbearia').fill(name)
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await page.waitForURL('**/onboarding/profile')
  await expect(page.getByRole('heading', { name: 'Personalize seu agendamento' })).toBeVisible()
  let upload = 0
  await context.route('https://i.ibb.co/**', route => route.fulfill({ path: 'public/brand/barbershop-hero.png', contentType: 'image/png' }))
  await page.route('**/api/images/upload', route => route.fulfill({ json: { url: `https://i.ibb.co/onboarding/${++upload}.png` } }))
  await page.getByLabel('Banner da barbearia', { exact: true }).setInputFiles('public/brand/barbershop-hero.png')
  await expect(page.getByRole('button', { name: 'Trocar imagem' })).toHaveCount(1)
  await page.getByLabel('Foto de perfil da barbearia', { exact: true }).setInputFiles('public/brand/headbarber_simbolo_duas_cores_transparente.png')
  await expect(page.getByRole('button', { name: 'Trocar imagem' })).toHaveCount(2)
  await page.getByLabel('Endereço completo').fill('Rua Inicial, 25, Centro, Curitiba - PR')
  await page.getByRole('button', { name: 'Concluir e entrar no painel' }).click()
  await page.waitForURL('**/dashboard')
  const slug = executeLocalSql(`select slug from public.barbershops where name='${name}'`)
  await page.goto('/dashboard/configuracoes')
  await page.getByRole('tab', { name: 'Perfil público' }).click()
  await expect(page.getByLabel('Endereço completo')).toHaveValue('Rua Inicial, 25, Centro, Curitiba - PR')
  await expect(page.getByRole('img', { name: 'Prévia: Banner da barbearia' })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Prévia: Foto de perfil da barbearia' })).toBeVisible()
  await page.getByLabel('Endereço completo').fill('Rua Atualizada, 50, Curitiba - PR')
  await page.getByRole('button', { name: 'Salvar perfil público' }).click()
  await expect(page.getByRole('status')).toContainText('salvo')
  await page.goto(`/booking/${slug}`)
  await expect(page.getByRole('img', { name: `Ambiente da ${name}` })).toBeVisible()
  await expect(page.getByRole('img', { name: `Foto de perfil da ${name}` })).toBeVisible()
  await expect(page.getByRole('link', { name: /Abrir no Google Maps/ })).toHaveAttribute('href', /Rua%20Atualizada/)
})

test('new shop may skip optional photos and address', async ({ page }) => {
  const fixture = await seedBookingFixture()
  await page.goto('/login')
  await page.locator('#login-email').fill(fixture.ownerEmail)
  await page.locator('#login-password').fill(fixture.ownerPassword)
  await page.locator('form').getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForURL('**/dashboard')
  await page.goto('/onboarding/profile')
  await page.getByRole('link', { name: 'Configurar depois' }).click()
  await page.waitForURL('**/dashboard')
  await page.goto(`/booking/${fixture.slug}`)
  await expect(page.getByRole('img', { name: 'Imagem padrão da barbearia' })).toBeVisible()
  await expect(page.getByRole('img', { name: /Iniciais de/ })).toHaveText('BE')
  await expect(page.getByRole('link', { name: /Abrir no Google Maps/ })).toHaveCount(0)
  executeLocalSql(`update public.barbershops set booking_avatar_url='/missing-avatar.png', booking_banner_url='/missing-banner.png' where id='${fixture.barbershopId}'`)
  await page.route('**/missing-*.png', route => route.fulfill({ status: 404, body: '' }))
  await page.reload()
  await expect(page.getByRole('img', { name: 'Imagem padrão da barbearia' })).toBeVisible()
  await expect(page.getByRole('img', { name: /Iniciais de/ })).toHaveText('BE')
})

test('initial profile setup requires authentication and the owner role', async ({ page }) => {
  await page.goto('/onboarding/profile')
  await expect(page).toHaveURL(/\/login/)
  const fixture = await seedBookingFixture()
  executeLocalSql(`update public.profiles set role='barber' where barbershop_id='${fixture.barbershopId}'`)
  await page.locator('#login-email').fill(fixture.ownerEmail)
  await page.locator('#login-password').fill(fixture.ownerPassword)
  await page.locator('form').getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForURL('**/dashboard')
  await page.goto('/onboarding/profile')
  await expect(page).toHaveURL(/\/dashboard$/)
})
